// Add smooth scrolling to all links
document.querySelectorAll('a[href^="#"]').forEach((anchor) => {
  anchor.addEventListener("click", function (e) {
    e.preventDefault();

    const targetId = this.getAttribute("href");
    if (targetId === "#") return;

    const targetElement = document.querySelector(targetId);
    if (targetElement) {
      window.scrollTo({
        top: targetElement.offsetTop - 80, // Offset for fixed header
        behavior: "smooth",
      });

      // Close mobile menu if open
      if (navMenu && navMenu.classList.contains("active")) {
        navMenu.classList.remove("active");
        if (mobileMenuToggle) {
          mobileMenuToggle.classList.remove("active");
        }
      }
    }
  });
});

// FAQ accordion functionality if present on the page
const faqItems = document.querySelectorAll(".faq-item");
if (faqItems.length > 0) {
  faqItems.forEach((item) => {
    const question = item.querySelector(".faq-question");
    question.addEventListener("click", () => {
      // Close all other open items
      faqItems.forEach((otherItem) => {
        if (otherItem !== item && otherItem.classList.contains("active")) {
          otherItem.classList.remove("active");
        }
      });

      // Toggle current item
      item.classList.toggle("active");
    });
  });
}

// Initialize tooltips if any
const tooltips = document.querySelectorAll("[data-tooltip]");
if (tooltips.length > 0) {
  tooltips.forEach((tooltip) => {
    tooltip.addEventListener("mouseenter", function () {
      const tooltipText = this.getAttribute("data-tooltip");
      const tooltipElement = document.createElement("div");
      tooltipElement.className = "tooltip";
      tooltipElement.textContent = tooltipText;
      document.body.appendChild(tooltipElement);

      const rect = this.getBoundingClientRect();
      tooltipElement.style.top =
        rect.top - tooltipElement.offsetHeight - 10 + "px";
      tooltipElement.style.left =
        rect.left + rect.width / 2 - tooltipElement.offsetWidth / 2 + "px";
      tooltipElement.style.opacity = "1";
    });

    tooltip.addEventListener("mouseleave", function () {
      const tooltipElement = document.querySelector(".tooltip");
      if (tooltipElement) {
        tooltipElement.remove();
      }
    });
  });
}

// Handle testimonial slider if present
const testimonialSlider = document.querySelector(".testimonial-slider");
if (testimonialSlider) {
  const testimonials = testimonialSlider.querySelectorAll(".testimonial");
  const prevButton = testimonialSlider.querySelector(".prev-testimonial");
  const nextButton = testimonialSlider.querySelector(".next-testimonial");
  let currentIndex = 0;

  function showTestimonial(index) {
    testimonials.forEach((testimonial, i) => {
      testimonial.style.display = i === index ? "block" : "none";
    });
  }

  if (prevButton) {
    prevButton.addEventListener("click", () => {
      currentIndex =
        (currentIndex - 1 + testimonials.length) % testimonials.length;
      showTestimonial(currentIndex);
    });
  }

  if (nextButton) {
    nextButton.addEventListener("click", () => {
      currentIndex = (currentIndex + 1) % testimonials.length;
      showTestimonial(currentIndex);
    });
  }

  // Initialize first testimonial
  showTestimonial(currentIndex);

  // Auto-rotate testimonials
  setInterval(() => {
    currentIndex = (currentIndex + 1) % testimonials.length;
    showTestimonial(currentIndex);
  }, 8000);
}

